const dictionaries: Record<SupportedLocale, Record<TranslationKey, string>> = {
  'zh-CN': zhCN,
  'en-US': enUS
};

export interface LocalizedMessage {
  key: TranslationKey;
  params?: TranslationParams;
}

export class LocalizedError extends Error {
  constructor(
    public readonly key: TranslationKey,
    public readonly params?: TranslationParams
  ) {
    super(translate('zh-CN', key, params));
    this.name = 'LocalizedError';
  }
}

export function normalizeLocalePreference(value: unknown): LocalePreference {
  return value === 'zh-CN' || value === 'en-US' || value === 'system' ? value : 'system';
}

export function resolveLocale(preference: LocalePreference, systemLocale: string | undefined): SupportedLocale {
  if (preference !== 'system') {
    return preference;
  }
  return (systemLocale || '').toLowerCase().startsWith('zh') ? 'zh-CN' : 'en-US';
}

export function translate(locale: SupportedLocale, key: TranslationKey, params: TranslationParams = {}): string {
  return dictionaries[locale][key].replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match
  );
}

export function localizedErrorMessage(locale: SupportedLocale, error: unknown): string {
  if (error instanceof LocalizedError) {
    return translate(locale, error.key, error.params);
  }
  return error instanceof Error ? error.message : String(error);
}
